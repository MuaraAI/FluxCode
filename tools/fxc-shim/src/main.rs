//! Minimal `fxc.exe` stand-in for building GPUI release binaries without the
//! Windows SDK. GPUI's build script runs:
//!
//! ```text
//! fxc /T <target> /E <entry> /Fh <out.h> /Vn <var> /O3 <file.hlsl>
//! ```
//!
//! and only reads the `const BYTE <var>[] = { ... };` array from the header.
//! The compiler itself is `D3DCompileFromFile` from `d3dcompiler_47.dll`,
//! which ships with Windows 10/11. Point GPUI at it with
//! `GPUI_FXC_PATH=<path to fxc-shim.exe>`.

use std::ffi::{c_void, CString, OsStr};
use std::os::windows::ffi::OsStrExt;
use std::process::exit;

type HResult = i32;

#[repr(C)]
struct BlobVtbl {
    query_interface: usize,
    add_ref: usize,
    release: unsafe extern "system" fn(*mut Blob) -> u32,
    get_buffer_pointer: unsafe extern "system" fn(*mut Blob) -> *const u8,
    get_buffer_size: unsafe extern "system" fn(*mut Blob) -> usize,
}

#[repr(C)]
struct Blob {
    vtbl: *const BlobVtbl,
}

type D3DCompileFromFile = unsafe extern "system" fn(
    file: *const u16,
    defines: *const c_void,
    include: *mut c_void,
    entry: *const i8,
    target: *const i8,
    flags1: u32,
    flags2: u32,
    code: *mut *mut Blob,
    errors: *mut *mut Blob,
) -> HResult;

extern "system" {
    fn LoadLibraryW(name: *const u16) -> *mut c_void;
    fn GetProcAddress(module: *mut c_void, name: *const i8) -> *mut c_void;
}

const D3DCOMPILE_OPTIMIZATION_LEVEL3: u32 = 1 << 15;
/// `D3D_COMPILE_STANDARD_FILE_INCLUDE`: resolve `#include` next to the source file.
const STANDARD_FILE_INCLUDE: *mut c_void = 1 as *mut c_void;

fn wide(s: &OsStr) -> Vec<u16> {
    s.encode_wide().chain(Some(0)).collect()
}

unsafe fn blob_bytes(b: *mut Blob) -> Vec<u8> {
    let v = &*(*b).vtbl;
    std::slice::from_raw_parts((v.get_buffer_pointer)(b), (v.get_buffer_size)(b)).to_vec()
}

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let (mut target, mut entry, mut out, mut var, mut file) = (None, None, None, None, None);
    let mut flags = 0u32;
    let mut i = 0;
    while i < args.len() {
        let a = args[i].as_str();
        let next = || args.get(i + 1).cloned();
        match a.to_ascii_lowercase().as_str() {
            "/t" | "-t" => { target = next(); i += 1; }
            "/e" | "-e" => { entry = next(); i += 1; }
            "/fh" | "-fh" => { out = next(); i += 1; }
            "/vn" | "-vn" => { var = next(); i += 1; }
            "/o3" | "-o3" => flags |= D3DCOMPILE_OPTIMIZATION_LEVEL3,
            _ if a.starts_with('/') || a.starts_with('-') => {
                eprintln!("fxc-shim: unsupported option {a}");
                exit(2);
            }
            _ => file = Some(a.to_string()),
        }
        i += 1;
    }
    let (Some(target), Some(entry), Some(out), Some(file)) = (target, entry, out, file) else {
        eprintln!("usage: fxc-shim /T <target> /E <entry> /Fh <out.h> [/Vn <name>] [/O3] <file>");
        exit(2);
    };
    let var = var.unwrap_or_else(|| format!("g_{entry}"));

    unsafe {
        let dll = LoadLibraryW(wide(OsStr::new("d3dcompiler_47.dll")).as_ptr());
        if dll.is_null() {
            eprintln!("fxc-shim: d3dcompiler_47.dll not found");
            exit(1);
        }
        let sym = GetProcAddress(dll, c"D3DCompileFromFile".as_ptr());
        if sym.is_null() {
            eprintln!("fxc-shim: D3DCompileFromFile missing");
            exit(1);
        }
        let compile: D3DCompileFromFile = std::mem::transmute(sym);
        let (e, t) = (CString::new(entry.clone()).unwrap(), CString::new(target).unwrap());
        let (mut code, mut errors) = (std::ptr::null_mut(), std::ptr::null_mut());
        let hr = compile(
            wide(OsStr::new(&file)).as_ptr(),
            std::ptr::null(),
            STANDARD_FILE_INCLUDE,
            e.as_ptr(),
            t.as_ptr(),
            flags,
            0,
            &mut code,
            &mut errors,
        );
        if !errors.is_null() {
            eprint!("{}", String::from_utf8_lossy(&blob_bytes(errors)));
            ((*(*errors).vtbl).release)(errors);
        }
        if hr < 0 || code.is_null() {
            eprintln!("fxc-shim: compiling {entry} failed (HRESULT {hr:#010x})");
            exit(1);
        }
        let bytes = blob_bytes(code);
        ((*(*code).vtbl).release)(code);

        let mut h = format!("// generated by fxc-shim\n\nconst BYTE {var}[] =\n{{\n");
        for (n, chunk) in bytes.chunks(16).enumerate() {
            if n > 0 {
                h.push_str(",\n");
            }
            let line: Vec<String> = chunk.iter().map(|b| format!("{b:3}")).collect();
            h.push_str("    ");
            h.push_str(&line.join(", "));
        }
        h.push_str("\n};\n");
        if let Err(err) = std::fs::write(&out, h) {
            eprintln!("fxc-shim: cannot write {out}: {err}");
            exit(1);
        }
    }
}
