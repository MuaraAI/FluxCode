#[cfg(test)]
mod tests {
    use super::ID;

    /// Every `{slot}` of the English text appears in the Indonesian one too.
    #[test]
    fn slots_match() {
        let slots = |s: &str| {
            let mut v: Vec<String> = s.split('{').skip(1).filter_map(|p| p.split_once('}').map(|(n, _)| n.to_string())).collect();
            v.sort();
            v
        };
        for (en, id) in ID {
            assert_eq!(slots(en), slots(id), "{en}");
        }
        let mut keys: Vec<&str> = ID.iter().map(|p| p.0).collect();
        keys.sort();
        let n = keys.len();
        keys.dedup();
        assert_eq!(n, keys.len(), "duplicate key");
    }
}
